/**
 * Notation census: how often each spacecraft-dynamics convention appears in MathType (or
 * MathBlocks) Word documents, to pick palette defaults from the author's own writing.
 * Run: pnpm tsx tools/notation-census.ts <a.docx> [b.docx …]  → local/NOTATION-CENSUS.md (gitignored: it is derived from your documents)
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename } from "node:path";
import { convertDocx } from "@mathblocks/mathtype";
import { findForms, formLabel } from "../app/src/lib/notation";

const files = process.argv.slice(2);
if (!files.length) throw new Error("usage: notation-census <a.docx> [b.docx …]");

interface Eq {
  file: string;
  number: string | null;
  latex: string;
}
const eqs: Eq[] = [];
for (const f of files) {
  const r = convertDocx(new Uint8Array(readFileSync(f)));
  for (const e of r.equations) if (e.latex) eqs.push({ file: basename(f), number: e.number, latex: e.latex });
}

/** Convention → patterns that identify it in LaTeX. */
const TOPICS: { topic: string; forms: [string, RegExp][] }[] = [
  {
    topic: "Physical vector (arrow / harpoon / bold)",
    forms: [
      ["bold with harpoon \\overrightharpoon{\\mathbf{r}}", /\\overrightharpoon\{\\mathbf\{/g],
      ["bold with arrow \\vec{\\mathbf{r}}", /\\vec\{\\mathbf\{/g],
      ["arrow \\vec{r}", /\\vec\{(?!\\mathbf|\\boldsymbol|\\vec)/g],
      ["harpoon \\overrightharpoon{r}", /\\overrightharpoon\{(?!\\mathbf|\\boldsymbol)/g],
      ["bold Greek \\boldsymbol{\\omega}", /\\boldsymbol\{\\[a-z]+\}/g],
    ],
  },
  {
    topic: "Vectrix / frame",
    forms: [
      ["\\vec{\\mathbf{F}} (Hughes vectrix, capital)", /\\vec\{\\mathbf\{[A-Z]\}\}/g],
      ["\\vec{\\mathcal{F}}", /\\vec\{\\mathcal\{/g],
      ["\\mathcal{F}_B", /\\mathcal\{F\}_/g],
      ["\\{\\hat{b}\\}", /\\\{\s*\\hat\{/g],
    ],
  },
  {
    topic: "Unit / basis vectors",
    forms: [
      ["\\hat{s}_i (plain)", /\\hat\{[a-z]\}_/g],
      ["\\hat{\\mathbf{b}}_i (bold)", /\\hat\{\\mathbf\{/g],
      ["\\vec{\\mathbf{s}}_i (bold arrow, subscript)", /\\vec\{\\mathbf\{[a-z]\}\}_\{?\d/g],
    ],
  },
  {
    topic: "Transpose",
    forms: [
      ["bold T ^{\\mathbf{T}}", /\^\{\\mathbf\{T\}\}/g],
      ["^{T}", /\^\{?T\}?(?![a-z])/g],
      ["^{\\top}", /\^\{?\\top/g],
      ["^{\\mathsf{T}}", /\^\{\\mathsf\{T\}\}/g],
    ],
  },
  {
    topic: "Direction cosine / rotation matrix",
    forms: [
      ["\\mathbf{C}_{ba} (Hughes)", /\\mathbf\{C\}_\{?[a-z]{1,2}\}?/g],
      ["\\mathbf{C}_{BN} (capital frames)", /\\mathbf\{C\}_\{[A-Z]{2}\}/g],
      ["[BN] (Schaub)", /\\left\[\s*[A-Z]{2}\s*\\right\]|\[[A-Z]{2}\]/g],
      ["\\mathbf{A} (Markley attitude matrix)", /\\mathbf\{A\}(?![a-z])/g],
      ["\\mathbf{R}", /\\mathbf\{R\}(?![a-z])/g],
      ["\\mathbf{C}_1/2/3(θ)", /\\mathbf\{C\}_\{?[123]\}?\s*\(/g],
    ],
  },
  {
    topic: "Skew-symmetric (cross-product) matrix",
    forms: [
      ["a^{\\times} (Hughes)", /\^\{?\\times\}?/g],
      ["[\\tilde{\\omega}] / \\tilde{\\omega} (Schaub)", /\\tilde\{/g],
      ["[\\omega\\times] (Markley)", /\[\s*\\?[a-zA-Z{}\\]+\s*\\times\s*\]/g],
    ],
  },
  {
    topic: "Quaternion / Euler parameters",
    forms: [
      ["scalar-first q_0 / \\beta_0", /(?:q|\\beta)_\{?0\}?/g],
      ["scalar-last q_4", /q_\{?4\}?/g],
      ["\\eta (scalar) with \\boldsymbol{\\epsilon} (Hughes)", /\\eta(?![a-z])/g],
      ["quaternion product \\otimes", /\\otimes/g],
      ["quaternion product \\odot", /\\odot/g],
      ["MRP \\boldsymbol{\\sigma}", /\\boldsymbol\{\\sigma\}/g],
    ],
  },
  {
    topic: "Time derivative in a frame",
    forms: [
      ["\\frac{{}^{N}\\mathrm{d}}{\\mathrm{d}t} (Schaub)", /\\frac\{\{\}\^/g],
      ["\\overset{\\circ}{} (Hughes, relative to rotating frame)", /\\overset\{\\circ\}/g],
      ["\\dot{} (dot)", /\\dot\{/g],
      ["\\frac{\\mathrm{d}}{\\mathrm{d}t}", /\\frac\{\\mathrm\{d\}\}\{\\mathrm\{d\}t\}/g],
    ],
  },
  {
    topic: "Components in a frame",
    forms: [
      ["bold column \\mathbf{c} (Hughes)", /\\mathbf\{[a-z]\}(?!\})/g],
      ["{}^{B}\\boldsymbol{\\omega} (Schaub)", /\{\}\^\{?[A-Z]\}?/g],
      ["\\{\\omega\\}_B", /\\\{[^}]*\\\}_/g],
    ],
  },
  {
    topic: "Dyadic / inertia",
    forms: [
      ["\\vec{\\vec{\\mathbf{I}}} (double arrow)", /\\vec\{\\vec\{/g],
      ["\\bar{\\bar{I}}", /\\bar\{\\bar\{/g],
      ["\\underline{\\underline{I}}", /\\underline\{\\underline\{/g],
      ["\\mathbf{I} / \\mathbf{J} matrix", /\\mathbf\{[IJ]\}/g],
      ["[I] (Schaub)", /\[\s*I\s*\]/g],
    ],
  },
];

const md: string[] = [
  "# Notation census",
  "",
  `Generated by \`pnpm tsx tools/notation-census.ts\` from ${files.map((f) => `\`${basename(f)}\``).join(", ")}: ${eqs.length} equations (display and inline).`,
  "",
];
for (const t of TOPICS) {
  md.push(`## ${t.topic}`, "", "| Form | Uses | Equations | Example |", "|---|---|---|---|");
  for (const [label, re] of t.forms) {
    const hits = eqs.filter((e) => (e.latex.match(re) ?? []).length);
    const uses = eqs.reduce((n, e) => n + (e.latex.match(re) ?? []).length, 0);
    const ex = hits[0];
    md.push(`| ${label.replace(/\|/g, "\\|")} | ${uses} | ${hits.length} | ${ex ? `${ex.number ?? ""} \`${ex.latex.slice(0, 80).replace(/\|/g, "\\|")}\`` : "—"} |`);
  }
  md.push("");
}
md.push("## All decorated-symbol forms", "", "| Form | Uses | Letters |", "|---|---|---|");
for (const f of findForms(eqs.map((e) => e.latex))) md.push(`| ${formLabel(f.key)} | ${f.count} | ${[...f.letters.keys()].join(" ").replace(/\|/g, "\\|")} |`);
md.push("");
mkdirSync(new URL("../local/", import.meta.url), { recursive: true });
writeFileSync(new URL("../local/NOTATION-CENSUS.md", import.meta.url), md.join("\n"));
console.log(`${eqs.length} equations → local/NOTATION-CENSUS.md`);
