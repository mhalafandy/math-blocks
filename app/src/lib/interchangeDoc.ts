/**
 * docs/LATEX-INTERCHANGE.md, generated from the parser's real support: every command listed parses
 * without an error or an "unknown command" warning (commands that do not are left out). Regenerate
 * with `pnpm interchange:doc`; CI fails when the committed file differs.
 */
import { KINDS } from "@mathblocks/math-core";
import { latexCommands, parseLatex } from "@mathblocks/math-latex";
import { DISPLAY_STYLE, DYADIC_LETTERS } from "./latexInterchange";

const parsesCleanly = (latex: string) => !parseLatex(latex).diagnostics.some((d) => d.severity === "error" || /^Unknown command/.test(d.message));
const code = (s: string) => "`" + s + "`";
const list = (cmds: string[]) => cmds.map(code).join(", ");
/** Only what the parser accepts; the rest is dropped (and so not promised). */
const verified = (cmds: string[], example: (c: string) => string) => cmds.filter((c) => parsesCleanly(example(c)));

export function interchangeDocument(): string {
  const c = latexCommands;
  const symbols = Object.entries(c.SYMBOLS);
  const byType = (t: string) => verified(symbols.filter(([, d]) => (t === "ident" ? d.type === "ident" || d.type === "ordinary" : d.type === t)).map(([k]) => "\\" + k), (x) => x);
  const kinds = KINDS.filter((k) => parsesCleanly(`\\${k.macro}${"{x}".repeat(k.args)}`));
  const structures: [string, string][] = [
    ["\\frac{a}{b}", "fraction (also \\dfrac, \\tfrac, \\cfrac)"],
    ["\\binom{n}{k}", "binomial (also \\dbinom, \\tbinom)"],
    ["\\sqrt{x}", "square root"],
    ["\\sqrt[3]{x}", "n-th root"],
    ["x^{2}", "superscript"],
    ["x_{i}", "subscript"],
    ["x_{i}^{2}", "both"],
    ["\\operatorname{tr}", "upright operator name"],
    ["\\overset{a}{=}", "symbol over (also \\stackrel)"],
    ["\\underset{a}{=}", "symbol under"],
    ["\\overbrace{a+b}", "brace over"],
    ["\\underbrace{a+b}", "brace under"],
    ["\\boxed{x}", "box"],
    ["\\left( x \\right)", "stretchy delimiters (\\left, \\right, \\middle)"],
    ["\\bigl( x \\bigr)", "fixed-size delimiters (\\big, \\Big, \\bigg, \\Bigg and their l/r forms)"],
    ["\\text{ for all } x", "text (also \\textrm, \\textit, \\textbf, \\mbox)"],
    ["x'", "prime (ASCII apostrophe; '' for a double prime)"],
  ];
  const envs = [...c.MATRIX_ENVS].filter((e) => parsesCleanly(`\\begin{${e}}a&b\\\\c&d\\end{${e}}`));
  const aligned = [...c.ALIGNED_ENVS].filter((e) => parsesCleanly(e.startsWith("alignat") ? `\\begin{${e}}{1}a&=b\\end{${e}}` : `\\begin{${e}}a&=b\\\\&=c\\end{${e}}`));
  const otherEnvs = ["cases", "dcases", "array"].filter((e) => parsesCleanly(e === "array" ? "\\begin{array}{cc}a&b\\end{array}" : `\\begin{${e}}a&x>0\\\\b&x\\le0\\end{${e}}`));
  const accents = verified(Object.keys(c.ACCENTS).map((k) => "\\" + k), (x) => `${x}{a}`);
  const fonts = verified(Object.keys(c.FONTS).map((k) => "\\" + k), (x) => `${x}{a}`);
  const spaces = verified(Object.keys(c.SPACES).map((k) => (k === " " ? "\\ " : "\\" + k)), (x) => `a${x} b`);
  const nary = verified(Object.keys(c.NARY).map((k) => "\\" + k), (x) => `${x}_{a}^{b} x`);
  const functions = verified(Object.keys(c.FUNCTIONS).map((k) => "\\" + k), (x) => `${x} x`);
  const delimiters = verified(Object.keys(c.DELIMITERS).filter((d) => d !== "."), (d) => `\\left${d} x \\right.`);
  const ignored = verified([...c.IGNORED].filter((k) => !["left", "right", "big", "Big", "bigg", "Bigg", "bigl", "bigr", "Bigl", "Bigr", "biggl", "biggr", "Biggl", "Biggr"].includes(k)).map((k) => "\\" + k), (x) => `${x} a`);
  const structureRows = structures.filter(([ex]) => parsesCleanly(ex));

  return `# LaTeX interchange convention

<!-- Generated by \`pnpm interchange:doc\` (app/src/lib/interchangeDoc.ts) from the parser's real support.
     Do not edit by hand: CI fails when this file differs from what the generator writes. -->

This is the exact form a Word document must follow so that MathBlocks' **Convert LaTeX** turns it into
finished equations, equation numbers and cross-references in one pass, with no manual fixing. It is
written for whoever produces the documents (for example, a transcription of handwritten pages into the
thesis template).

## 1. Paragraphs

| What | Paragraph | Text of the paragraph |
|---|---|---|
| Inline equation | any (in the sentence) | \`… the vector $\\pvec{c}_1$ is …\` |
| Display, unnumbered | style **${DISPLAY_STYLE}**, alone | TAB \`$$…$$\` |
| Display, numbered | style **${DISPLAY_STYLE}**, alone | TAB \`$$…$$\` TAB \`\\label{eq:KEY}\` |
| Multi-line, one number | style **${DISPLAY_STYLE}**, alone | TAB \`$$\\begin{aligned} a &= b \\\\ &= c \\end{aligned}$$\` TAB \`\\label{eq:KEY}\` |
| Reference with brackets | in the sentence | \`\\eqref{eq:KEY}\` → (A.3) |
| Reference, number only | in the sentence | \`\\ref{eq:KEY}\` → A.3 |
| Numbering prefix | its own paragraph, right after each chapter or appendix heading | \`\\mbnumbering{3}\` or \`\\mbnumbering{A}\` |

Rules:

- TAB is a real tab character (Word's Tab key), not spaces.
- Never type an equation number: \`\\label{eq:KEY}\` gives it. MathBlocks computes it from the position
  and the last \`\\mbnumbering\`: (3.1), (3.2)… in chapter 3; (A.1), (A.2)… in appendix A.
- KEY: lowercase ASCII letters, digits and hyphens, starting with \`eq:\` — e.g. \`eq:a-first-moment\`.
  Each KEY once per document. References may come before or after the equation they point to.
- \`\\mbnumbering{…}\` takes a chapter number (\`3\`) or one capital letter for an appendix (\`A\` = first
  appendix). It is needed after every chapter or appendix heading whose equations are numbered.
- Inside \`$…$\` and \`$$…$$\`: plain ASCII — straight quotes, \`-\` for minus, \`'\` for primes.
- One display equation per paragraph; nothing else in that paragraph except the TABs and the label.
- \`\\(…\\)\` is accepted for inline and \`\\[…\\]\` for display, but \`$…$\` and \`$$…$$\` are preferred.
- A literal dollar sign in text is written \`\\$\`.

Example (one appendix):

\`\`\`text
Appendix A                                                    ← Heading (unnumbered in the template)
\\mbnumbering{A}
The first moment of body $\\body{B}_1$ about its origin is defined in \\eqref{eq:a-first-moment}.
⇥$$\\pvec{c}_1 = \\int_{\\body{B}_1} \\pvec{r}\\,\\mathrm{d}m$$⇥\\label{eq:a-first-moment}     ← ${DISPLAY_STYLE}
⇥$$\\pvec{c}_1 = \\vectrix{F}^{\\T}\\cmat{c}_1$$                                   ← ${DISPLAY_STYLE}, unnumbered
⇥$$\\begin{aligned} \\cmat{c}_1 &= \\int \\cmat{r}\\,\\mathrm{d}m \\\\ &= m\\cmat{r}_c \\end{aligned}$$⇥\\label{eq:a-centre}
Equation \\ref{eq:a-centre} gives the centre of mass.
\`\`\`

## 2. What Convert LaTeX does

1. **Pre-flight report, before anything is written:** the counts (inline, display, numbered,
   references, markers) and every problem with the text around it — parse errors, unknown commands,
   duplicate labels, unresolved references, malformed display paragraphs, typed numbers that differ
   from the computed ones. You choose: stop, or convert the valid items.
2. **Writes, as one Ctrl+Z** (a backup is made first for large documents):
   - inline equations as MathBlocks objects on the text baseline;
   - display equations as MathBlocks objects in the paragraph's own style (centred on its centre tab);
   - numbered ones with a number field at the right tab and a bookmark named from the label
     (\`eq:a-first-moment\` → \`_MBEq_a_first_moment\`);
   - \`\\mbnumbering\` as the hidden numbering marker (its paragraph becomes hidden);
   - references as cross-reference fields (Ctrl+click jumps to the equation); unresolved ones stay as
     text, highlighted, and are listed;
   - then every number and reference is updated.
3. **Re-running converts only what is left** (converted equations are no longer text; numbers continue
   from the ones already converted; references may point at equations converted earlier).

## 3. Older forms that are converted too

- Display paragraphs with a typed number — TAB \`$$…$$\` TAB \`(A.3)\` — get a number field instead of
  the text; the report warns when the computed number differs from the typed one.
- MathType-style notation is mapped to notation kinds:
  - \`\\mathbf{\\overset{\\scriptscriptstyle\\rightharpoonup}{c}}\` → \`\\pvec{c}\`
  - \`\\vec{\\mathbf{S}}\` (capital) → \`\\vectrix{S}\`; for ${[...DYADIC_LETTERS].map(code).join(" and ")} → \`\\dyadic{…}\`
  - \`\\left[\\begin{array}{…}…\\end{array}\\right]\` → \`bmatrix\` (\`( )\` → \`pmatrix\`, \`| |\` → \`vmatrix\`)

## 4. What Word does to typed LaTeX, undone before parsing

Smart quotes → straight quotes; en dash, em dash, minus sign → \`-\`; non-breaking and other special
spaces → space; manual line breaks → space; soft hyphens and zero-width characters → removed;
autocorrect symbols → their LaTeX (… → \`\\ldots\`, → → \`\\rightarrow\`, ⇒ → \`\\Rightarrow\`, © → \`(c)\`).

## 5. Supported LaTeX (exactly what the parser accepts)

Anything not listed here is reported in the pre-flight as an unknown command and not converted.

### Notation kinds (preferred for vectors, frames, matrices)

| Macro | Meaning |
|---|---|
${kinds.map((k) => `| ${code(`\\${k.macro}${k.args ? k.argNames.map((a) => `{${a}}`).join("") : ""}`)} | ${k.name} |`).join("\n")}

An index goes outside the kind: \`\\pvec{c}_1\`, \`\\uvec{s}_2\`. The transpose is \`^{\\T}\`.

### Structures

| Write | For |
|---|---|
${structureRows.map(([ex, what]) => `| ${code(ex)} | ${what} |`).join("\n")}

### Environments

- Matrices: ${list(envs.map((e) => e))} — rows end with \`\\\\\`, cells are separated by \`&\`.
- Multi-line (one number for the whole block): ${list(aligned)}.
- Other: ${list(otherEnvs)}.

### Symbols

- Letters and ordinary symbols: ${list(byType("ident"))}
- Binary operators: ${list(byType("binary"))}
- Relations and arrows: ${list(byType("relation"))}
- Punctuation: ${list(byType("punctuation"))}
- Large operators (limits with \`_\` and \`^\`): ${list(nary)}
- Functions: ${list(functions)}

### Accents, fonts, spaces, delimiters

- Accents: ${list(accents)}
- Fonts: ${list(fonts)}
- Spaces: ${list(spaces)}, \`~\`
- Delimiters after \`\\left\`/\`\\right\`/\`\\big…\`: ${list(delimiters)}, and \`.\` for none
- Accepted and ignored (size/style hints): ${list(ignored)}
`;
}
